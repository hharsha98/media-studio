#!/usr/bin/env node
/**
 * Maintainer tool (friends never run this). Rebuilds
 * plugins/media-studio/skills/media-studio/assets-manifest.json from a local
 * checkout of latent-spaces/brag that is sitting on the pinned commit.
 *
 *   node tools/build-assets-manifest.mjs /path/to/brag-checkout
 *
 * The manifest stores each file's SHA-256 and size. scripts/setup.mjs downloads the
 * files from raw.githubusercontent.com at that exact commit and refuses any file
 * whose hash differs. Music, music cues and SFX are NOT stored in this repository.
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const repo = process.argv[2];
if (!repo) { console.error("usage: node tools/build-assets-manifest.mjs <brag checkout>"); process.exit(1); }
const git = (...a) => execFileSync("git", ["-C", repo, ...a], { encoding: "utf8" }).trim();
const commit = git("rev-parse", "HEAD");
if (git("status", "--porcelain")) { console.error("checkout is not clean; refusing"); process.exit(1); }
const base = path.join(repo, "skills", "brag", "assets");

const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
  e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]);
const entry = (abs) => {
  const buf = fs.readFileSync(abs);
  return { path: path.relative(base, abs).split(path.sep).join("/"), sha256: crypto.createHash("sha256").update(buf).digest("hex"), bytes: buf.length };
};
const all = walk(base).sort();
const music = all.filter((p) => /\/music\/[^/]+\.mp3$/.test(p.split(path.sep).join("/")));
const cues = all.filter((p) => /\/music\/cues\//.test(p.split(path.sep).join("/")) || /sfx-analysis\.(json|md)$/.test(p));
const sfx = all.filter((p) => /\/sfx\/.+\.(ogg|wav)$/.test(p.split(path.sep).join("/")));

const manifest = {
  note: "Generated by tools/build-assets-manifest.mjs. Do not edit by hand.",
  source: {
    repo: "latent-spaces/brag",
    commit,
    urlBase: `https://raw.githubusercontent.com/latent-spaces/brag/${commit}/skills/brag/assets/`,
  },
  groups: {
    music: {
      label: "Music: 5 tracks, 'Happy Beats / Business Moves' by Sascha Ende (ende.app)",
      license: "CC BY 4.0",
      credit: "Music: Sascha Ende (ende.app), CC BY 4.0",
      files: music.map(entry),
    },
    cues: {
      label: "Beat and cue files for the 5 tracks, plus the SFX guide (small text files)",
      license: "MIT (latent-spaces/brag)",
      credit: "",
      files: cues.map(entry),
    },
    sfx: {
      label: "Sound effects library (UI, impact, casino, keyboard)",
      license: "CC0 (Kenney.nl; keyboard set by unicae_games)",
      credit: "",
      files: sfx.map(entry),
    },
  },
};
const out = path.join(path.dirname(new URL(import.meta.url).pathname), "..", "plugins", "media-studio", "skills", "media-studio", "assets-manifest.json");
fs.writeFileSync(out, JSON.stringify(manifest, null, 2) + "\n");
for (const [k, g] of Object.entries(manifest.groups)) {
  console.log(k, g.files.length, "files", g.files.reduce((s, f) => s + f.bytes, 0), "bytes");
}
console.log("commit", commit, "->", out);
